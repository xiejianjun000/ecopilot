export type IconName = keyof typeof ICON_MAP

export interface IconProps extends Omit<TablerIconsProps, 'name'> {
  name: IconName | string
  size?: number
  className?: string
}

export function Icon({ name, size = 16, className, ...rest }: IconProps) {
  const iconKey = ICON_MAP[name]
  if (!iconKey) {
    // console.warn(`[Icon] unknown icon: "${name}"`)
    return null
  }
  const Component = Icons[iconKey] as React.ComponentType<TablerIconsProps> | undefined
  if (!Component) {
    return null
  }
  return <Component size={size} className={className} {...rest} />
}
