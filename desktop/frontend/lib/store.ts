/**
 * 带重试的数据拉取（解决 mount 初始化时序：ensureAuthToken 可能尚未就绪）
 * - 首次失败或返回空数组 → 等 1s 重试 1 次
 * - 最终仍失败 → 打印 console.error 并返回空数组（不阻塞 UI）
 * - 仅供 AppProvider 内部使用；导出用于单元测试
 */
export async function fetchWithRetry<T>(
  label: string,
  fetcher: () => Promise<T[]>,
  retries = 2,
  delayMs = 1000,
): Promise<T[]> {
  const attempt = async (n: number): Promise<T[]> => {
    try {
      const result = await fetcher()
      if (result.length > 0) return result
      if (n < retries) {
        await new Promise(r => setTimeout(r, delayMs))
        return attempt(n + 1)
      }
      return []
    } catch (err) {
      console.error(`[store] ${label} 拉取失败 (第${n}次):`, err)
      if (n < retries) {
        await new Promise(r => setTimeout(r, delayMs))
        return attempt(n + 1)
      }
      return []
    }
  }
  return attempt(1)
}

